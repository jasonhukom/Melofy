void updateDisplay() {
  display.clearDisplay();
  display.setTextSize();
  display.setTextColor(SSD1306_WHITE);

  if(currentAsset == 0) {
    display.setCursor(20, 0);
    display.println("Asset 1 : Minecraft Avatar");

    display.drawBitmap(48, 20, asset1, 32, 32, SSD1306_WHITE);
  } else {
    display.setCursor(10, 0);
    display.println("Asset 2 : Cute Cat (Eatable)");

    display.drawBitmap(48, 20, asset2, 32, 32, SSD1306_WHITE);
  }

  display.display(); 
};

void setup() {
  // put your setup code here, to run once:
  Serial.begin(115200);
  pinMode(BUTTON_PIN, INPUT_PULLUP);
  pinMode(BUZZER_PIN, OUTPUT);

  if (!display.begin(SSD1306_SWITCHCAPVCC, 0x3C)) {
    for(;;);
  }

  updateDisplay();
}

void loop() {
  bool currentButtonState = digitalRead(BUTTON_PIN);

  if(lastButtonState == HIGH && currentButtonState == LOW) {
    tone(BUZZER_PIN, 1000);
    delay(100);
    noTone(BUZZER_PIN);

    currentAsset = (currentAsset == 0) ? 1 : 0;

    updateDisplay();
    delay(150);
  }
  lastButtonState = currentButtonState;
  delay(10); // this speeds up the simulation
}
